/**
 * Retrieve converter tool configuration by tool ID or route slug safely.
 */
export function getConverterConfig(idOrSlug: string): ConverterToolConfig | null {
  if (!idOrSlug) return CONVERTER_TOOLS['image-converter'];

  const clean = idOrSlug.toLowerCase().replace(/^\/+|\/+$/g, '');

  if (CONVERTER_TOOLS[clean]) {
    return CONVERTER_TOOLS[clean];
  }

  // Fallback matching by normalized route or id
  const foundByRoute = Object.values(CONVERTER_TOOLS).find((tool) => {
    const toolRouteClean = tool.route.toLowerCase().replace(/^\/+|\/+$/g, '');
    const toolIdClean = tool.id.toLowerCase().replace(/^\/+|\/+$/g, '');
    return toolRouteClean === clean || toolIdClean === clean;
  });

  return foundByRoute || null;
}

/**
 * Utility to validate if a File matches a converter config's accepted input criteria.
 */
export function validateFileInput(
  file: File,
  config: ConverterToolConfig
): { isValid: boolean; error: string | null } {
  if (!file) {
    return { isValid: false, error: 'No file provided.' };
  }

  // 1. Max size check
  if (config.maxFileSizeMB > 0) {
    const maxBytes = config.maxFileSizeMB * 1024 * 1024;
    if (file.size > maxBytes) {
      return {
        isValid: false,
        error: `File size exceeds the maximum allowed limit of ${config.maxFileSizeMB} MB.`
      };
    }
  }

  // 2. Format / extension check
  if (config.inputFormats.includes('ALL')) {
    return { isValid: true, error: null };
  }

  const name = file.name.toLowerCase();
  const mime = file.type.toLowerCase();

  // Extension check
  const extMatch = config.fileExtensions.some((ext) => ext !== '*' && name.endsWith(ext.toLowerCase()));
  
  // MIME check
  const mimeMatch = config.mimeTypes.some((m) => {
    if (m === '*/*') return true;
    if (m.endsWith('/*')) {
      const base = m.split('/')[0];
      return mime.startsWith(`${base}/`);
    }
    return mime === m.toLowerCase();
  });

  if (extMatch || mimeMatch) {
    return { isValid: true, error: null };
  }

  const acceptedList = config.inputFormats.join(', ');
  return {
    isValid: false,
    error: `Invalid file format. This tool accepts ${acceptedList} files.`
  };
}
